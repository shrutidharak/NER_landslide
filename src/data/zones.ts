export const getRiskColor = (risk: RiskLevel): string => {
  switch (risk) {
    case 'LOW': return '#16a34a';
    case 'MEDIUM': return '#d97706';
    case 'HIGH': return '#ea580c';
    case 'CRITICAL': return '#dc2626';
  }
};

export const getRiskBg = (risk: RiskLevel): string => {
  switch (risk) {
    case 'LOW': return '#dcfce7';
    case 'MEDIUM': return '#fef3c7';
    case 'HIGH': return '#ffedd5';
    case 'CRITICAL': return '#fee2e2';
  }
};

export const getRiskTextColor = (risk: RiskLevel): string => {
  switch (risk) {
    case 'LOW': return '#15803d';
    case 'MEDIUM': return '#b45309';
    case 'HIGH': return '#c2410c';
    case 'CRITICAL': return '#b91c1c';
  }
};

