const makeHistory = (base: number, variance: number, count = 24) =>
  Array.from({ length: count }, (_, i) => ({
    time: subHours(now, count - i - 1),
    value: Math.max(0, base - variance + Math.random() * variance * 2 * ((i + 1) / count)),
  }));

